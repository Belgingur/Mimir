#!/usr/bin/env node
/**
 * Generate src/lib/timeZoneCoordinates.ts: where each IANA time zone is.
 *
 * The map guesses a first-time reader's region from the browser's time zone,
 * which needs no permission prompt and no request. The coordinates come from
 * the tz database's zone.tab (each zone's principal city).
 *
 * Browsers do not always report the current IANA id. Chrome reports CLDR's ids,
 * some of which are older names ("Atlantic/Faeroe", "Asia/Calcutta",
 * "Europe/Kiev"), so the old names are included as aliases, taken from the
 * links in tzdata.zi. Since 2022 the database also links zones that merely
 * share clock rules ("Iceland" links to Africa/Abidjan), so a zone listed in
 * zone.tab always keeps its own place, and the few renamed ids whose link now
 * crosses a border are pointed at their own place by RELOCATED below.
 *
 * Usage (or `npm run timezones:build`):
 *   node scripts/build-timezones.mjs [zoneinfo-dir] [out-file]
 *   (defaults: /usr/share/zoneinfo, src/lib/timeZoneCoordinates.ts)
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const zoneinfo = process.argv[2] ?? "/usr/share/zoneinfo";
const outFile = process.argv[3] ?? "src/lib/timeZoneCoordinates.ts";

/** Old ids whose tzdata.zi link goes to another country; their own place. */
const RELOCATED = {
  "Africa/Timbuktu": "Africa/Bamako",
  "America/Coral_Harbour": "America/Atikokan",
  "Antarctica/South_Pole": "Antarctica/McMurdo",
  "Atlantic/Jan_Mayen": "Arctic/Longyearbyen",
  "Pacific/Ponape": "Pacific/Pohnpei",
  "Pacific/Truk": "Pacific/Chuuk",
  "Pacific/Yap": "Pacific/Chuuk",
};

/** "+DDMM" / "+DDMMSS" (or DDD for longitude) to decimal degrees. */
function iso6709(part, degreeDigits) {
  const sign = part[0] === "-" ? -1 : 1;
  const digits = part.slice(1);
  const deg = Number(digits.slice(0, degreeDigits));
  const min = Number(digits.slice(degreeDigits, degreeDigits + 2));
  const sec = Number(digits.slice(degreeDigits + 2) || 0);
  return sign * (deg + min / 60 + sec / 3600);
}

function parseCoordinates(text) {
  const match = /^([+-]\d+)([+-]\d+)$/.exec(text);
  if (!match) throw new Error(`bad coordinates ${text}`);
  const round = (n) => Math.round(n * 10) / 10;
  return [round(iso6709(match[1], 2)), round(iso6709(match[2], 3))];
}

const zones = new Map();
for (const line of readFileSync(join(zoneinfo, "zone.tab"), "utf8").split("\n")) {
  if (!line || line.startsWith("#")) continue;
  const [, coordinates, zone] = line.split("\t");
  zones.set(zone, parseCoordinates(coordinates));
}

const version = readFileSync(join(zoneinfo, "tzdata.zi"), "utf8")
  .split("\n", 1)[0]
  .replace(/^# version /, "");

const aliases = new Map();
for (const line of readFileSync(join(zoneinfo, "tzdata.zi"), "utf8").split("\n")) {
  if (!line.startsWith("L ")) continue;
  const [, target, alias] = line.split(" ");
  // Country names ("Iceland", "GB") and fixed offsets are never reported by a
  // browser as a resolved zone, and the former link by clock rules, not place.
  if (!alias.includes("/") || alias.startsWith("Etc/") || zones.has(alias)) continue;
  const place = RELOCATED[alias] ?? target;
  if (!zones.has(place)) {
    console.error(`skip ${alias}: ${place} has no coordinates`);
    continue;
  }
  aliases.set(alias, place);
}
for (const [alias, place] of Object.entries(RELOCATED)) {
  if (!zones.has(place)) throw new Error(`RELOCATED ${alias} -> ${place} is not in zone.tab`);
}

const sorted = (map) => [...map.entries()].sort(([a], [b]) => a.localeCompare(b));
const out = [
  `// Generated by scripts/build-timezones.mjs from tzdata ${version} on ${new Date().toISOString().slice(0, 10)}.`,
  "// Do not edit by hand; re-run the script to pick up a newer tz database.",
  "",
  "/** [lat, lon] of each IANA zone's principal city, to 0.1°, from zone.tab. */",
  "export const TIME_ZONE_COORDINATES: Record<string, readonly [number, number]> = {",
  ...sorted(zones).map(([zone, [lat, lon]]) => `  ${JSON.stringify(zone)}: [${lat}, ${lon}],`),
  "};",
  "",
  "/** Older ids browsers may still report, mapped to the zone in the same place. */",
  "export const TIME_ZONE_ALIASES: Record<string, string> = {",
  ...sorted(aliases).map(([alias, zone]) => `  ${JSON.stringify(alias)}: ${JSON.stringify(zone)},`),
  "};",
  "",
];
writeFileSync(outFile, out.join("\n"));
console.error(`wrote ${outFile}: ${zones.size} zones, ${aliases.size} aliases (tzdata ${version})`);
